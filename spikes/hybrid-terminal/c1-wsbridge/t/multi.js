const { Client, sleep } = require('./lib'); const path = require('path'); const work = path.join(__dirname, '..', 'work');
const tail = (c, n = 3) => c.screen().filter(Boolean).slice(-n).join(' / ');
const sz = c => `${c.term.cols}x${c.term.rows}`;
(async () => {
  const mac = new Client('mac', { cols: 120, rows: 40 }), phone = new Client('phone', { cols: 50, rows: 30 });
  await mac.connect(); await phone.connect();
  mac.send({ type: 'spawn', kind: 'shell', script: `stty size; trap 'echo WINCH $(stty size)' WINCH; echo ready; while :; do sleep 0.2; done`, cwd: work, cols: 120, rows: 40 });
  await mac.until(() => mac.last('spawned')); const id = mac.last('spawned').id;
  await mac.attach(id, 120, 40); await phone.attach(id, 50, 30);
  console.log('1. mac attached first at 120x40; phone attached asking for 50x30');
  console.log(`   phone told: ${JSON.stringify(phone.last('attached'))}`);
  console.log(`   emulator sizes: mac ${sz(mac)}, phone ${sz(phone)} (phone adopts the PTY size, not its own viewport)`);
  console.log(`   both see output? mac: "${tail(mac, 2)}"  | phone: "${tail(phone, 2)}"`);
  mac.send({ type: 'resize', cols: 120, rows: 40 }); await sleep(300);
  phone.send({ type: 'resize', cols: 50, rows: 30 }); await sleep(600);
  console.log('2. phone sends resize 50x30 while the mac is the active driver');
  console.log(`   PTY unchanged? last size msg: ${JSON.stringify(mac.last('size') ?? 'none')}  mac ${sz(mac)} phone ${sz(phone)}`);
  phone.input('x'); await sleep(900); await phone.flush(); await mac.flush();
  console.log('3. phone types a key -> phone becomes driver, PTY resizes to 50x30');
  console.log(`   mac ${sz(mac)} phone ${sz(phone)}; last size msg: ${JSON.stringify(phone.last('size'))}`);
  console.log(`   program saw: "${tail(phone, 2)}"`);
  console.log(`   mac screen shows the same: "${tail(mac, 2)}"`);
  mac.input('y'); await sleep(900); await phone.flush(); await mac.flush();
  console.log('4. mac types a key -> mac becomes driver, PTY back to 120x40');
  console.log(`   mac ${sz(mac)} phone ${sz(phone)}; program saw: "${tail(mac, 1)}"`);
  const same = JSON.stringify(mac.screen()) === JSON.stringify(phone.screen());
  console.log(`5. screens identical on both clients: ${same}`);
  phone.kill(); await sleep(500);
  console.log(`6. phone disconnects -> PTY stays at ${sz(mac)}, mac unaffected; session still alive`);
  mac.send({ type: 'list' }); await mac.until(() => mac.last('sessions')); console.log('   alive:', mac.last('sessions').sessions.map(s => s.alive));
  process.exit(0);
})().catch(e => { console.error('FAIL', e); process.exit(1); });
